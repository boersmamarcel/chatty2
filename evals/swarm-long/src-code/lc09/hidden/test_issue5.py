import unittest

from verspec.lockfile import LockError, dump_lock, parse_lock

LOCK = """# generated by verspec

requests == 2.31.0
left-pad==1.3.0  # pinned for the build
  Flask==3.0.0
urllib3 ==2.0.7#security
"""


class ParseLockTest(unittest.TestCase):
    def test_parse(self):
        pins = parse_lock(LOCK)
        self.assertEqual(list(pins), ["requests", "left-pad", "flask", "urllib3"])
        self.assertEqual(str(pins["left-pad"]), "1.3.0")
        self.assertEqual(str(pins["urllib3"]), "2.0.7")
        self.assertEqual(dump_lock(pins, header=""),
                         "flask==3.0.0\nleft-pad==1.3.0\nrequests==2.31.0\nurllib3==2.0.7\n")

    def test_duplicate(self):
        text = "# lock\nFlask==3.0.0\n\nrequests==2.31.0\nflask == 3.0.1\n"
        with self.assertRaises(LockError) as ctx:
            parse_lock(text)
        self.assertEqual(str(ctx.exception), "line 5: duplicate package 'flask'")

    def test_malformed(self):
        cases = [
            ("a==1.0.0\nb 1.0.0\n", 2),
            ("# x\n\na==1.0.0==2.0.0\n", 3),
            ("==1.0.0\n", 1),
            ("a==1.0.0\nb==\n", 2),
            ("a==1.0.0\n# c\nb==1.0\n", 3),
            ("a = 1.0.0\n", 1),
        ]
        for text, line in cases:
            with self.assertRaises(LockError, msg=text) as ctx:
                parse_lock(text)
            self.assertTrue(str(ctx.exception).startswith("line %d: " % line),
                            "%r -> %s" % (text, ctx.exception))

    def test_empty(self):
        self.assertEqual(list(parse_lock("")), [])
        self.assertEqual(list(parse_lock("# only a comment\n\n")), [])


if __name__ == "__main__":
    unittest.main()
